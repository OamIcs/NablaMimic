"""Code generator: a fused Warp kernel for the RNE bias forces of a fixed MuJoCo tree (written for the G1).

MuJoCo Warp evaluates the tree level by level. For a fixed model the tree can be unrolled at code-generation time:
generate_rne_bias emits a kernel that, in one thread per world, computes what mjw com_vel + rne(flg_acc=False) compute
from given com-based dof axes and inertias, with the model's constants baked in as literals. The formulas follow
mujoco_warp/_src/smooth.py (MuJoCo Warp, Apache-2.0, The Newton Developers; see THIRD_PARTY_NOTICES.md). Its Warp
adjoint is the reverse-mode VJP g1_fast.adjoint_patch uses.

Supported: one free joint on body 1, every other body with exactly one hinge joint at its origin, no mocap
bodies, gravity enabled. Anything else raises. Quaternions are wp.vec4 in MuJoCo's (w, x, y, z) order.

  from nablamimic.g1_fast.smooth_gen import build_rne_bias
  mod = build_rne_bias(mjm)        # writes and imports the generated module (cached by source hash)

Generated modules go to $G1_FAST_GEN_DIR, else <$XDG_CACHE_HOME or ~/.cache>/nablamimic/g1_fast_gen.
"""

import hashlib
import importlib.util
import os
from pathlib import Path

import mujoco
import numpy as np

GEN_DIR = Path(os.environ.get("G1_FAST_GEN_DIR")
               or Path(os.environ.get("XDG_CACHE_HOME") or Path.home() / ".cache") / "nablamimic" / "g1_fast_gen")

HEADER = '''# generated by nablamimic.g1_fast.smooth_gen -- do not edit
import warp as wp

vec10 = wp.types.vector(length=10, dtype=float)


@wp.func
def qmul(u: wp.vec4, v: wp.vec4) -> wp.vec4:
    return wp.vec4(u[0] * v[0] - u[1] * v[1] - u[2] * v[2] - u[3] * v[3],
                   u[0] * v[1] + u[1] * v[0] + u[2] * v[3] - u[3] * v[2],
                   u[0] * v[2] - u[1] * v[3] + u[2] * v[0] + u[3] * v[1],
                   u[0] * v[3] + u[1] * v[2] - u[2] * v[1] + u[3] * v[0])


@wp.func
def qrot(v: wp.vec3, q: wp.vec4) -> wp.vec3:
    s = q[0]
    u = wp.vec3(q[1], q[2], q[3])
    return 2.0 * (wp.dot(u, v) * u) + (s * s - wp.dot(u, u)) * v + 2.0 * s * wp.cross(u, v)


@wp.func
def qnorm(q: wp.vec4) -> wp.vec4:
    return q / wp.length(q)


@wp.func
def axang(axis: wp.vec3, angle: float) -> wp.vec4:
    s = wp.sin(angle * 0.5)
    return wp.vec4(wp.cos(angle * 0.5), axis[0] * s, axis[1] * s, axis[2] * s)


@wp.func
def qmat(q: wp.vec4) -> wp.mat33:
    q00 = q[0] * q[0]
    q01 = q[0] * q[1]
    q02 = q[0] * q[2]
    q03 = q[0] * q[3]
    q11 = q[1] * q[1]
    q12 = q[1] * q[2]
    q13 = q[1] * q[3]
    q22 = q[2] * q[2]
    q23 = q[2] * q[3]
    q33 = q[3] * q[3]
    return wp.mat33(q00 + q11 - q22 - q33, 2.0 * (q12 - q03), 2.0 * (q13 + q02),
                    2.0 * (q12 + q03), q00 - q11 + q22 - q33, 2.0 * (q23 - q01),
                    2.0 * (q13 - q02), 2.0 * (q23 + q01), q00 - q11 - q22 + q33)


@wp.func
def cinert(xm: wp.mat33, inert: wp.vec3, mass: float, dif: wp.vec3) -> vec10:
    t = xm * wp.diag(inert) * wp.transpose(xm)
    return vec10(t[0, 0] + mass * (dif[1] * dif[1] + dif[2] * dif[2]),
                 t[1, 1] + mass * (dif[0] * dif[0] + dif[2] * dif[2]),
                 t[2, 2] + mass * (dif[0] * dif[0] + dif[1] * dif[1]),
                 t[0, 1] - mass * dif[0] * dif[1],
                 t[0, 2] - mass * dif[0] * dif[2],
                 t[1, 2] - mass * dif[1] * dif[2],
                 mass * dif[0], mass * dif[1], mass * dif[2], mass)


@wp.func
def inert_vec(i: vec10, v: wp.spatial_vector) -> wp.spatial_vector:
    return wp.spatial_vector(
        i[0] * v[0] + i[3] * v[1] + i[4] * v[2] - i[8] * v[4] + i[7] * v[5],
        i[3] * v[0] + i[1] * v[1] + i[5] * v[2] + i[8] * v[3] - i[6] * v[5],
        i[4] * v[0] + i[5] * v[1] + i[2] * v[2] - i[7] * v[3] + i[6] * v[4],
        i[8] * v[1] - i[7] * v[2] + i[9] * v[3],
        i[6] * v[2] - i[8] * v[0] + i[9] * v[4],
        i[7] * v[0] - i[6] * v[1] + i[9] * v[5])


@wp.func
def mcross(u: wp.spatial_vector, v: wp.spatial_vector) -> wp.spatial_vector:
    u0 = wp.vec3(u[0], u[1], u[2])
    u1 = wp.vec3(u[3], u[4], u[5])
    v0 = wp.vec3(v[0], v[1], v[2])
    v1 = wp.vec3(v[3], v[4], v[5])
    return wp.spatial_vector(wp.cross(u0, v0), wp.cross(u1, v0) + wp.cross(u0, v1))


@wp.func
def mcross_force(v: wp.spatial_vector, f: wp.spatial_vector) -> wp.spatial_vector:
    v0 = wp.vec3(v[0], v[1], v[2])
    v1 = wp.vec3(v[3], v[4], v[5])
    f0 = wp.vec3(f[0], f[1], f[2])
    f1 = wp.vec3(f[3], f[4], f[5])
    return wp.spatial_vector(wp.cross(v0, f0) + wp.cross(v1, f1), wp.cross(v0, f1))


@wp.func
def sdot(a: wp.spatial_vector, b: wp.spatial_vector) -> float:
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2] + a[3] * b[3] + a[4] * b[4] + a[5] * b[5]

'''


def _f(x):
    return f"{float(np.float32(x))!r}"


def _v3(v):
    return f"wp.vec3({_f(v[0])}, {_f(v[1])}, {_f(v[2])})"


def _v4(v):
    return f"wp.vec4({_f(v[0])}, {_f(v[1])}, {_f(v[2])}, {_f(v[3])})"


def _check(mjm: mujoco.MjModel):
    nb = mjm.nbody
    FREE, HINGE = int(mujoco.mjtJoint.mjJNT_FREE), int(mujoco.mjtJoint.mjJNT_HINGE)
    if mjm.nmocap:
        raise ValueError("mocap bodies are not supported")
    if mjm.opt.disableflags & int(mujoco.mjtDisableBit.mjDSBL_GRAVITY):
        raise ValueError("gravity disabled is not supported")
    if mjm.body_jntnum[1] != 1 or mjm.jnt_type[mjm.body_jntadr[1]] != FREE or mjm.body_parentid[1] != 0:
        raise ValueError("body 1 must be the free root")
    for b in range(2, nb):
        j = mjm.body_jntadr[b]
        if mjm.body_jntnum[b] != 1 or mjm.jnt_type[j] != HINGE or np.any(mjm.jnt_pos[j] != 0):
            raise ValueError(f"body {b} must have one hinge joint at its origin")
        if mjm.body_parentid[b] == 0:
            raise ValueError(f"body {b}: only one tree is supported")


def generate_rne_bias(mjm: mujoco.MjModel) -> str:
    """Kernel g1_rne_bias(qvel, cdof, cinert) -> qfrc_bias: RNE bias forces at given com-based dof axes and inertias
    (MuJoCo Warp's com_vel + rne(flg_acc=False) with the tree unrolled). Its Warp adjoint, launched with the bias
    cotangent, gives lam^T d(qfrc_bias)/d(qvel) in one reverse pass (cdof and cinert held fixed)."""
    _check(mjm)
    nb, nv = mjm.nbody, mjm.nv
    g = mjm.opt.gravity
    L = ["@wp.kernel",
         "def g1_rne_bias(qvel: wp.array2d(dtype=float), cdof: wp.array2d(dtype=wp.spatial_vector),",
         "                cinert: wp.array2d(dtype=vec10), bias_out: wp.array2d(dtype=float)):",
         "    w = wp.tid()"]
    A = L.append
    for d in range(nv):
        A(f"    cd{d} = cdof[w, {d}]")
    for b in range(1, nb):
        A(f"    ci{b} = cinert[w, {b}]")
    A("    cv = cd0 * qvel[w, 0] + cd1 * qvel[w, 1] + cd2 * qvel[w, 2]")
    for k in range(3, 6):
        A(f"    cdd{k} = mcross(cv, cd{k})")
    A("    cv1 = cv + cd3 * qvel[w, 3] + cd4 * qvel[w, 4] + cd5 * qvel[w, 5]")
    for b in range(2, nb):
        d, p = mjm.body_dofadr[b], mjm.body_parentid[b]
        A(f"    cdd{d} = mcross(cv{p}, cd{d})")
        A(f"    cv{b} = cv{p} + cd{d} * qvel[w, {d}]")
    A(f"    ca1 = wp.spatial_vector(0.0, 0.0, 0.0, {_f(-g[0])}, {_f(-g[1])}, {_f(-g[2])})"
      " + cdd3 * qvel[w, 3] + cdd4 * qvel[w, 4] + cdd5 * qvel[w, 5]")
    for b in range(2, nb):
        d, p = mjm.body_dofadr[b], mjm.body_parentid[b]
        A(f"    ca{b} = ca{p} + cdd{d} * qvel[w, {d}]")
    for b in range(1, nb):
        A(f"    cf{b} = inert_vec(ci{b}, ca{b}) + mcross_force(cv{b}, inert_vec(ci{b}, cv{b}))")
    for b in range(nb - 1, 1, -1):
        A(f"    cf{mjm.body_parentid[b]} = cf{mjm.body_parentid[b]} + cf{b}")
    for d in range(nv):
        A(f"    bias_out[w, {d}] = sdot(cd{d}, cf{mjm.dof_bodyid[d]})")
    return HEADER + "\n".join(L) + "\n"


def _load(src: str, stem: str, cache_dir=None):
    """Write the generated source (once, named by its hash) and import it."""
    h = hashlib.sha1(src.encode()).hexdigest()[:12]
    cache_dir = Path(cache_dir or GEN_DIR)
    cache_dir.mkdir(parents=True, exist_ok=True)
    path = cache_dir / f"{stem}_{h}.py"
    if not path.exists():
        path.write_text(src)
    spec = importlib.util.spec_from_file_location(f"{stem}_{h}", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def build_rne_bias(mjm: mujoco.MjModel, cache_dir=None):
    """Generate (if needed) and import the g1_rne_bias module for this model."""
    return _load(generate_rne_bias(mjm), "g1_rne_bias", cache_dir)
